"""Write the EVAL-ONLY twins of experiments_md 20261003_05 §5 item 32e: the Lyft oracle 25769 per platform (LIDAR_CONFIG
64 / 40), the Pandar64 spin oracle 26389 and the full-length PandarGT flash oracle (29328 scored as 29329), each under the
OSENS-2 arms (height, pitch, background, foreground, ground) and, on Lyft, the density arms. ANALYSIS.

Pitch twins are NAMED by the ground ahead (pitchp1 = the ground rises 1 deg ahead, as OSENS-2). Lyft's sensor x points
backward (LIDAR_TOP yaw 176-179 deg, 20261004_02), so its twins carry PITCH_DEG = -d about x; PandaSet's loader frame has
x forward. analysis/groupcheck_32e_cpu_check.py verifies each sign on real frames.

Runs inside the container from ST3D/tools (it resolves the bases):
    python analysis/make_groupcheck_configs_32e.py
"""
import copy
import os
import sys

import yaml

sys.path.insert(0, '.')
import _init_path  # noqa: F401,E402

OUT = 'cfgs/da-ieee-access-analysis/groupcheck'
LYFT = 'cfgs/da-ieee-access/centerpoint-sourceonly-lyft2lyft.yaml'
SPIN = 'cfgs/da-ieee-access/centerpoint-pandaset-spin2spin.yaml'
FLASH = 'cfgs/da-ieee-access/centerpoint-pandaset-flash2flash.yaml'
# base -> (twin stem, pivot of the pitch arms in the loader frame, sign of PITCH_DEG for "the ground rises ahead",
#          extra DATA_CONFIG_TAR keys every twin of this base carries)
BASES = {
    'lyft-l64': (LYFT, 'centerpoint-sourceonly-lyft2lyft-l64', [0.0, 0.0, 1.6], -1.0, {'LIDAR_CONFIG': 64}),
    'lyft-l40': (LYFT, 'centerpoint-sourceonly-lyft2lyft-l40', [0.0, 0.0, 1.6], -1.0, {'LIDAR_CONFIG': 40}),
    'spin': (SPIN, 'centerpoint-pandaset-spin2spin', [0.0, 0.0, 1.88], 1.0, {}),
    'flash': (FLASH, 'centerpoint-pandaset-flash2flash', [0.0, 0.0, 1.88], 1.0, {}),
}
REGION = {
    'bgkeep050': {'REGION_THIN': {'SIDE': 'background', 'KEEP': 0.5}, 'BOX_MARGIN': 0.25},
    'bgkeep025': {'REGION_THIN': {'SIDE': 'background', 'KEEP': 0.25}, 'BOX_MARGIN': 0.25},
    'fgkeep050': {'REGION_THIN': {'SIDE': 'foreground', 'KEEP': 0.5}, 'BOX_MARGIN': 0.25},
    'fgkeep025': {'REGION_THIN': {'SIDE': 'foreground', 'KEEP': 0.25}, 'BOX_MARGIN': 0.25},
    'groundrm020': {'GROUND_REMOVE_DIST': 0.2, 'BOX_MARGIN': 0.25},
}


def resolved(path):
    from easydict import EasyDict
    from pcdet.config import cfg_from_yaml_file
    return cfg_from_yaml_file(path, EasyDict())


def plain(x):
    """EasyDict / numpy-free copy for yaml."""
    if isinstance(x, dict):
        return {k: plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [plain(v) for v in x]
    return x


def density_processor(processor, ratio):
    """The base's DATA_PROCESSOR with a test-time uniform keep inserted before voxelisation (the 20261010_01 arm)."""
    out = []
    for p in plain(processor):
        if p['NAME'] == 'transform_points_to_voxels':
            out.append({'NAME': 'sample_points', 'NUM_POINTS': {'train': -1, 'test': -1}, 'RATIO': {'test': ratio}})
        out.append(p)
    assert sum(p['NAME'] == 'sample_points' for p in out) == 1, 'base already samples points'
    return out


def arms(key):
    base, stem, pivot, sign, extra = BASES[key]
    tar = resolved(base).DATA_CONFIG_TAR
    shift = [float(v) for v in tar.SHIFT_COOR]
    out = {}
    if key.startswith('lyft'):
        out['asscored'] = {}
        for r, tag in ((0.75, 'ratio075'), (0.5, 'ratio050'), (0.25, 'ratio025')):
            out[tag] = {'DATA_PROCESSOR': density_processor(tar.DATA_PROCESSOR, r)}
    for dz, tag in ((-0.30, 'dzm030'), (0.30, 'dzp030')):
        out[tag] = {'SHIFT_COOR': [shift[0], shift[1], round(shift[2] + dz, 4)]}
    for d, tag in ((-1, 'pitchm1'), (1, 'pitchp1'), (-2, 'pitchm2'), (2, 'pitchp2')):
        out[tag] = {'EVAL_OSENS2': {'PITCH_DEG': float(sign * d), 'SENSOR_ORIGIN': pivot, 'FORWARD_AXIS': 'x'}}
    for tag, block in REGION.items():
        out[tag] = {'EVAL_OSENS2': copy.deepcopy(block)}
    return {tag: dict(extra, **keys) for tag, keys in out.items()}, base, stem


def main():
    os.makedirs(OUT, exist_ok=True)
    for key in BASES:
        twins, base, stem = arms(key)
        for tag, keys in twins.items():
            path = os.path.join(OUT, '%s-%s.yaml' % (stem, tag))
            with open(path, 'w') as f:
                f.write('# EVAL-ONLY twin of %s for experiments_md 20261003_05 §5 item 32e (%s, %s).\n'
                        '# Generated by analysis/make_groupcheck_configs_32e.py. ANALYSIS.\n' % (base, key, tag))
                yaml.safe_dump({'_BASE_CONFIG_': base, 'DATA_CONFIG_TAR': keys}, f, sort_keys=False,
                               default_flow_style=None)
            print(path)


if __name__ == '__main__':
    main()
