def density_row(job_hist):
    """Lyft-64 D: the Lyft-40 C1-analog's operators (sample_points_hist_based to nuScenes TRAIN, then drop_empty_gt_boxes)
    on the 64-beam frames, with the histograms measured once by the stats job (fixed files) instead of at startup."""
    h = json.load(open(HIST))
    oracle = load(L64_ORACLE)
    proc = plain(oracle.DATA_CONFIG.DATA_PROCESSOR)
    names = [p['NAME'] for p in proc]
    k = names.index('shuffle_points') + 1
    proc = proc[:k] + [{'NAME': 'sample_points_hist_based', 'MIN_HIST_BIN_FRACTION': 0.01},
                       {'NAME': 'drop_empty_gt_boxes', 'MIN_POINTS': 1}] + proc[k:]
    header = (wrap(PREAMBLE % ('lyft64', TARGET['lyft64'][4], HIST, job_hist)) +
              '# This row: D, A1 density (not a TRAIN_FACTOR_SWAP arm): the Lyft-40 C1-analog 30313\'s operators on the 64-beam\n'
              '# frames - per-range-bin GLOBAL thinning to nuScenes TRAIN (sample_points_hist_based, 50 bins to 75 m,\n'
              '# MIN_HIST_BIN_FRACTION 0.01) and the processor-stage recount right after it (drop_empty_gt_boxes). The two\n'
              '# histograms are the files below, measured ONCE by the stats job with the function train.py\'s on-the-fly path\n'
              '# calls (point_calibration.compute_range_histogram, 1000 strided frames each): this source in training mode, and\n'
              '# nuScenes TRAIN through the eval-mode view of 30313\'s target block (calibration_target_config). In-range points\n'
              '# per frame %.0f -> %.0f; expected kept share %.3f; %d of %d bins below 1. Fixed files instead of\n'
              '# HIST_DIST_ON_THE_FLY because the on-the-fly path measures the target on DATA_CONFIG_TAR, which here is\n'
              '# Lyft-64 val (the evaluation set), not nuScenes.\n'
              % (h['src_points_per_frame'], h['tgt_points_per_frame'], h['expected_kept_share'], h['bins_below_1'],
                 len(h['rate'])))
    body = {'_BASE_CONFIG_': L64_ORACLE,
            'DATA_CONFIG': {'POINT_CALIB_TAR': 'nuscenes', 'HIST_DIST_LYFT_PATH': h['files'][0],
                            'HIST_DIST_NUSCENES_PATH': h['files'][1], 'DATA_PROCESSOR': proc}}
    dump(A + 'factorswap-lyft64/centerpoint-factorswap-lyft64-d-density.yaml', header, body)


def resolved_twin(source_cfg, target, tar_shift=None, note=''):
    """The source row's resolved config with DATA_CONFIG_TAR = the target oracle's resolved one."""
    src = plain(load(source_cfg))
    for k in ('ROOT_DIR', 'LOCAL_RANK'):
        src.pop(k, None)
    tar = plain(load(TARGET[target][0]).DATA_CONFIG_TAR)
    if tar_shift is not None:
        tar['SHIFT_COOR'] = [0.0, 0.0, float(tar_shift)]
    src['DATA_CONFIG_TAR'] = tar
    return src


def eval_twins(stats):
    twins = [  # (target, file stem, source config, jobs, note)
        ('pandaset', 'evalonly-p-on-spin', 'cfgs/da-ieee-access/centerpoint-ringpattern-pandaset2nuscenes.yaml',
         'P 28034 / 28279, epoch 115', 'the reused P rows (nuScenes scan pattern + recount)'),
        ('pandaset', 'evalonly-c1-on-spin', 'cfgs/da-ieee-access/centerpoint-global-fovcut-recount-pandaset2nuscenes.yaml',
         'C1-analog 28041 / 28280, epoch 115', 'the reused C1-analog rows (vertical FOV + per-range-bin density + recount)'),
        ('lyft40', 'evalonly-p-on-lyft40', 'cfgs/da-ieee-access/centerpoint-ringpattern-lyft40-lyft2nuscenes.yaml',
         'P 30312 / 30363, epoch 30', 'the reused Lyft-40 P rows'),
        ('lyft40', 'evalonly-c1-on-lyft40', 'cfgs/da-ieee-access/centerpoint-global-recount-lyft40-lyft2nuscenes.yaml',
         'C1-analog 30313 / 30364, epoch 30', 'the reused Lyft-40 C1-analog rows'),
    ]
    for target, stem, src, jobs, what in twins:
        header = ('# EVAL-ONLY twin (experiments_md 20261003_05 §5 item 34): %s (%s) scored on the target\'s val with the target\n'
                  '# oracle\'s evaluation block. FULLY RESOLVED, generated by analysis/make_factorswap_pl_configs.py: %s\n'
                  '# resolved, DATA_CONFIG_TAR replaced by the resolved DATA_CONFIG_TAR of %s. Never trained on.\n'
                  % (what, jobs, src, TARGET[target][0]))
        dump(os.path.join(TARGET[target][2], 'centerpoint-factorswap-%s-%s.yaml' % (TARGET[target][3], stem)), header,
             resolved_twin(src, target))
    # (c) the source-only control: nuScenes oracle 25743 epoch 20 on each target's val, the target's label-free height
    for target in ('pandaset', 'lyft64', 'lyft40'):
        tar = load(TARGET[target][0]).DATA_CONFIG_TAR
        if target == 'pandaset':
            shift, why = None, ('SHIFT_COOR %.2f, the PandaSet config value (label-free: the TRAIN z-mode, uda_legality_rule '
                                '"SHIFT_COOR is legal"; rule G from this stats job gives %.3f, within 5 cm)'
                                % (tar.SHIFT_COOR[2], -1.815 + 1.75 - stats['pandaset']['ground']['height_raw_frame_m']['median']))
        else:
            g = stats[target]['height_rule_g']
            shift = round(g['target_shift_rule_g'], 2)
            why = ('SHIFT_COOR %.2f by rule G (g_nus %.3f + 1.75 - g_tgt %.3f, TRAIN clouds, 20261007_01\'s estimator: the\n'
                   '# label-free height rule), NOT the oracle\'s %.2f, which is the median Car box BASE (20260922_03 §1,\n'
                   '# label-derived)' % (shift, g['g_nuscenes_raw'], g['g_target_raw'], g['target_shift_config']))
        header = ('# EVAL-ONLY twin (experiments_md 20261003_05 §5 item 34, "gap per target"): the nuScenes oracle 25743\n'
                  '# (centerpoint-sourceonly-nuscenes.yaml, epoch 20, W&B wfdcq75s) scored on %s val = the source-only\n'
                  '# control; gap = O_T - this. FULLY RESOLVED, generated by analysis/make_factorswap_pl_configs.py: the nuScenes\n'
                  '# oracle resolved, DATA_CONFIG_TAR = the resolved DATA_CONFIG_TAR of %s, with\n# %s.\n'
                  '# Class map: the model is single-ontology (ONTOLOGY kitti, plain CLASS_NAMES), so scoring maps kitti -> the\n'
                  '# target through get_ontology_mapping, exactly as the target\'s own oracle; map_head_per_dataset_to_<ds> applies\n'
                  '# to prefixed (head_per_dataset) CLASS_NAMES only.\n' % (target, TARGET[target][0], why))
        dump(os.path.join(TARGET[target][2], 'centerpoint-factorswap-%s-evalonly-nuscenes-oracle-on-%s.yaml'
                          % (TARGET[target][3], TARGET[target][3])), header, resolved_twin(NUS_ORACLE, target, shift))
    # (d) background-1/2 val twins of each target oracle (for the oracle and its R9 row)
    for target, (oracle, _, d, short, desc) in TARGET.items():
        header = ('# EVAL-ONLY twin (experiments_md 20261003_05 §5 item 34, the R9 matched-cut check, as 31b): %s, its evaluation\n'
                  '# cloud with points outside every GT box enlarged by 0.25 m kept at 1/2 (EVAL_OSENS2 REGION_THIN, the\n'
                  '# osens2/...-bgkeep050 arm). Score the oracle AND its r9-bg050 row with it: R9_cut >= O_cut + 2 means the\n'
                  '# training cut leaks the box positions.\n' % desc)
        dump(os.path.join(d, 'centerpoint-factorswap-%s-evalbg050.yaml' % short), header,
             {'_BASE_CONFIG_': oracle, 'DATA_CONFIG_TAR': {'EVAL_OSENS2': {
                 'REGION_THIN': {'SIDE': 'background', 'KEEP': 0.5}, 'BOX_MARGIN': 0.25}}})


def main():
    jobs = {'pandaset': os.environ.get('JOB_PANDASET', '?'), 'lyft64': os.environ.get('JOB_LYFT64', '?'),
            'lyft40': os.environ.get('JOB_LYFT40', '?')}
    stats = {t: json.load(open(p)) for t, p in STATS.items()}
    for t in ('pandaset', 'lyft64', 'lyft40'):
        os.makedirs(TARGET[t][2], exist_ok=True)
        training_rows(t, stats[t], jobs[t])
    density_row(os.environ.get('JOB_HIST', '?'))
    eval_twins(stats)


if __name__ == '__main__':
    main()
