"""Write the EVAL-ONLY twins of the two nuScenes city oracles for experiments_md 20261003_05 §5 item 32c.

Each twin is a city oracle's own config (B->B or S->S, 20261022_06) plus exactly one target-side block, copied from the
full nuScenes oracle's twin of the same arm (sensitivity / osens2 / redraw configs used on 25743). ANALYSIS.

    python analysis/make_groupcheck_configs.py            # from ST3D/tools; writes cfgs/da-ieee-access-analysis/groupcheck/
"""
import os

import yaml

CITIES = {
    'boston2boston': 'cfgs/da-ieee-access/centerpoint-sourceonly-nuscenes-boston2boston.yaml',
    'singapore2singapore': 'cfgs/da-ieee-access/centerpoint-sourceonly-nuscenes-singapore2singapore.yaml',
}
S = 'cfgs/da-ieee-access-analysis/sensitivity/centerpoint-sourceonly-nuscenes'
O = 'cfgs/da-ieee-access-analysis/osens2/centerpoint-sourceonly-nuscenes-osens2'
# arm -> (full-oracle twin whose DATA_CONFIG_TAR block is copied, extra keys merged into that block)
ARMS = {
    'ringrows': (S + '-ringrows.yaml', None),
    'ringrandom': (S + '-ringrandom.yaml', None),
    'ringrandom-draw1': (S + '-ringrandom.yaml', ('EVAL_RING_THIN', {'DRAW': 1})),
    'ringrandom-draw2': (S + '-ringrandom.yaml', ('EVAL_RING_THIN', {'DRAW': 2})),
    'ratio050': (S + '-ratio050.yaml', None),
    'ratio025': (S + '-ratio025.yaml', None),
    'dzm030': (O + '-dzm030.yaml', None),
    'dzp030': (O + '-dzp030.yaml', None),
    'pitchm1': (O + '-pitchm1.yaml', None),
    'pitchp1': (O + '-pitchp1.yaml', None),
    'bgkeep025': (O + '-bgkeep025.yaml', None),
    'fgkeep050': (O + '-fgkeep050.yaml', None),
    'groundrm020': (O + '-groundrm020.yaml', None),
}
OUT = 'cfgs/da-ieee-access-analysis/groupcheck'


def main():
    os.makedirs(OUT, exist_ok=True)
    for city, base in CITIES.items():
        for arm, (src, extra) in ARMS.items():
            with open(src) as f:
                tar = yaml.safe_load(f)['DATA_CONFIG_TAR']
            if extra is not None:
                tar[extra[0]] = dict(tar[extra[0]], **extra[1])
            path = os.path.join(OUT, 'centerpoint-sourceonly-nuscenes-%s-%s.yaml' % (city, arm))
            with open(path, 'w') as f:
                f.write('# EVAL-ONLY twin of %s for experiments_md 20261003_05 §5 item 32c (%s):\n'
                        '# the DATA_CONFIG_TAR block of %s on the city oracle. Generated by\n'
                        '# analysis/make_groupcheck_configs.py. ANALYSIS.\n' % (base, arm, src))
                yaml.safe_dump({'_BASE_CONFIG_': base, 'DATA_CONFIG_TAR': tar}, f, sort_keys=False,
                               default_flow_style=None)
            print(path)


if __name__ == '__main__':
    main()
