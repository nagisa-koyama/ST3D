"""Write a FLAT rule-B config: a Waymo-source pseudo-labelling config's TARGET slot pointed at Waymo VAL, through the
source's own resolved DATA_CONFIG (so the teacher sees its training input), for generate_pseudo_labels.py.

make_teacher_on_source_val_cfg.py cannot serve a Waymo source (it reads INFO_PATH, which the Waymo loader does not
use). This is its Waymo analogue for a RING_PATTERN teacher (experiments_md 20261017_06 §3):
  - DATA_CONFIG_TAR = the resolved source DATA_CONFIG, DATA_SPLIT val / val, SAMPLED_INTERVAL 5 / 5 (7,998 frames);
  - USE_PSEUDO_LABEL True (as every rule-B flat config; the generator never reads the stored GT);
  - RING_PATTERN.APPLY_AT_EVAL True: generate_pseudo_labels.py puts the set in EVAL mode before generating, and
    RING_PATTERN otherwise acts in training only, so without it the teacher would label the raw five-lidar cloud.

    python analysis/pseudo_label_threshold/make_teacher_on_waymo_val_cfg.py \
        --cfg_file cfgs/da-ieee-access/centerpoint-ringpattern-st3d-waymo2nuscenes.yaml \
        --out analysis/pseudo_label_threshold/cfgs/teacher_27807_on_waymo_val_int5_ringpattern.yaml
"""
import argparse
import copy
import sys
from pathlib import Path

import yaml
from easydict import EasyDict

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import _init_path  # noqa: F401,E402
from pcdet.config import cfg_from_yaml_file  # noqa: E402


def plain(o):
    if isinstance(o, dict):
        return {k: plain(v) for k, v in o.items() if k != '_BASE_CONFIG_'}
    if isinstance(o, (list, tuple)):
        return [plain(v) for v in o]
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cfg_file', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--interval', type=int, default=5)
    args = ap.parse_args()
    full = cfg_from_yaml_file(args.cfg_file, EasyDict())
    assert full.DATA_CONFIG.DATASET == 'WaymoDataset', 'the source is not Waymo'
    ds = copy.deepcopy(full.DATA_CONFIG)
    ds.DATA_SPLIT = {'train': 'val', 'test': 'val'}
    ds.SAMPLED_INTERVAL = {'train': args.interval, 'test': args.interval}
    ds.USE_PSEUDO_LABEL = True
    if ds.get('RING_PATTERN', None) is not None:
        ds.RING_PATTERN.APPLY_AT_EVAL = True
    full.DATA_CONFIG_TAR = ds
    out = plain(full)
    header = ('# GENERATED by make_teacher_on_waymo_val_cfg.py for rule B - do not edit or train with.\n'
              '# %s with DATA_CONFIG_TAR replaced by its own RESOLVED source DATA_CONFIG on Waymo VAL\n'
              '# (SAMPLED_INTERVAL %d), RING_PATTERN.APPLY_AT_EVAL True so the eval-mode generation pass serves the\n'
              "# teacher its training input (experiments_md 20261017_06 §3).\n" % (args.cfg_file, args.interval))
    with open(args.out, 'w') as f:
        f.write(header)
        yaml.safe_dump(out, f, sort_keys=False, default_flow_style=False)
    t = out['DATA_CONFIG_TAR']
    print('wrote', args.out)
    print('DATA_CONFIG_TAR:', t['DATASET'], t['DATA_SPLIT'], t['SAMPLED_INTERVAL'], 'SHIFT_COOR', t.get('SHIFT_COOR'),
          'RING_PATTERN', t.get('RING_PATTERN'))


if __name__ == '__main__':
    main()
