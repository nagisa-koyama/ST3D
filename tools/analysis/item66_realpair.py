# ---------------------------------------------------------------- after training
def parse_jobs(args):
    out = {}
    for a in args:
        k, v = a.split('=')
        m = re.match(r'(bn_A|all_A|bn_C|all_C)(\d+)$', k)
        out[(m.group(1), int(m.group(2)))] = int(v)
    return out


def manifest(jobs):
    import item38_kitti_rings as i38
    rows = []
    for (arm, seed), job in sorted(jobs.items()):
        r = i38.resolve('item66', ROWS[arm], seed, job, 'epoch_%d' % EPOCHS)
        if r['status'] == 'ok' and not Path(r['result']).exists():
            r['status'] = 'result.pkl missing'
        rows.append(r)
    return rows


def word(d, kind):
    """The pre-declared word for one comparison, from its per-seed differences d (two values)."""
    if kind == 'cut':
        if all(x >= 2 for x in d):
            return WORDS_CUT[0]
        if all(x <= -2 for x in d):
            return WORDS_CUT[1]
        if all(abs(x) < 1 for x in d):
            return WORDS_CUT[2]
        return WORDS_CUT[3]
    if all(abs(x) < 2 for x in d):
        return WORDS_BN[0]
    if all(x <= -2 for x in d):
        return WORDS_BN[1]
    if all(x >= 2 for x in d):
        return WORDS_BN[2]
    return WORDS_BN[3]


COMPARISONS = (('H_cut, BN only: bn_C - bn_A', 'bn_C', 'bn_A', 'cut'), ('H_cut, every weight: all_C - all_A', 'all_C', 'all_A', 'cut'),
               ('H_bn, rule A: bn_A - all_A', 'bn_A', 'all_A', 'bn'), ('H_bn, count balance: bn_C - all_C', 'bn_C', 'all_C', 'bn'))


def readings(rows):
    pooled = {(r['row'], r['seed']): r['pooled']['bev'] for r in rows}
    out = []
    for name, a, b, kind in COMPARISONS:
        d = [pooled[(ROWS[a], s)] - pooled[(ROWS[b], s)] for s in SEEDS]
        out.append(dict(name=name, diffs=d, word=word(d, kind)))
    return out


def cmd_read(path):
    rows = json.load(open(path))['rows']
    for r in sorted(rows, key=lambda r: (r['row'], r['seed'])):
        print('%-8s s%d pooled %6.2f (3D %6.2f) logged %s | %s%s' % (
            r['row'], r['seed'], r['pooled']['bev'], r['pooled']['3d'], r['logged_bev'],
            ' '.join('%6.2f' % g['bev'] for g in r['rings']), '' if r.get('reproduced') else '  NOT REPRODUCED'))
    for x in readings(rows):
        print('%s: %+.2f / %+.2f -> "%s"' % (x['name'], x['diffs'][0], x['diffs'][1], x['word']))


def cmd_check(dst, jobs):
    import torch
    import item58_bn_bound as m58
    import item59_bn_split as m59
    load = lambda p: torch.load(p, map_location='cpu')['model_state']   # noqa: E731
    pre = load(T_CKPT)
    out = {}
    for (arm, seed), job in sorted(jobs.items()):
        c = m58.compare(pre, load(m59.ckpt_of(job, EPOCHS)))
        c['ok'] = (not c['non_bn_differ'] and not c['missing']) if arm.startswith('bn') else None
        out['%s s%d' % (ROWS[arm], seed)] = dict(c, job=job, epoch=EPOCHS)
    json.dump(out, open(dst, 'w'), indent=1)
    for k, c in out.items():
        print('%s (job %d): non-BN tensors differing %d, BN tensors changed %d, key mismatch %d, counters %s -> %s' % (
            k, c['job'], len(c['non_bn_differ']), c['bn_changed'], len(c['missing']), c['counters'],
            {True: 'ok', False: 'FAILED', None: 'descriptive'}[c['ok']]))
    sys.exit(1 if any(c['ok'] is False for c in out.values()) else 0)


def main():
    a = sys.argv[1:]
    if a == ['base_config']:
        return cmd_base_config()
    if a == ['srcdens']:
        return cmd_srcdens()
    if a == ['cuts']:
        return cmd_cuts()
    if a == ['configs']:
        return cmd_configs()
    if a[:1] == ['check'] and len(a) >= 4 and a[2] == '--jobs':
        return cmd_check(a[1], parse_jobs(a[3:]))
    if a[:1] == ['manifest'] and len(a) >= 4 and a[2] == '--jobs':
        rows = manifest(parse_jobs(a[3:]))
        json.dump(rows, open(a[1], 'w'), indent=1)
        for r in rows:
            print(r['row'], r['seed'], r.get('job'), r['status'], r.get('logged_bev'))
        sys.exit(0 if all(r['status'] == 'ok' for r in rows) else 1)
    if a[:1] == ['read'] and len(a) == 2:
        return cmd_read(a[1])
    print(__doc__)
    sys.exit(2)


if __name__ == '__main__':
    main()
