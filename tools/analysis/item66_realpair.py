# ---------------------------------------------------------------- source density (nuScenes, in KITTI's camera sector)
def kitti_sector(infos):
    """(right, left) half-angles in radians of KITTI camera 2's horizontal FOV, from the medians of W, c_x, f_x over `infos`'
    calibrations: a direction at azimuth phi (x forward, y left) projects inside the image when -right <= phi <= left."""
    import numpy as np
    from pcdet.utils import calibration_kitti
    w, cx, fx = [], [], []
    for info in infos:
        cal = calibration_kitti.Calibration(KITTI / 'training' / 'calib' / ('%s.txt' % info['point_cloud']['lidar_idx']))
        w.append(float(info['image']['image_shape'][1])); cx.append(float(cal.P2[0, 2])); fx.append(float(cal.P2[0, 0]))
    W, CX, FX = float(np.median(w)), float(np.median(cx)), float(np.median(fx))
    return float(np.arctan((W - CX) / FX)), float(np.arctan(CX / FX)), dict(W=W, cx=CX, fx=FX)


def ego_azimuth(centres, ref_from_car):
    """Azimuth about the vehicle's forward axis (ego x forward, y left) of LiDAR-frame centres, via the frame's ref_from_car."""
    import numpy as np
    car_from_ref = np.linalg.inv(np.asarray(ref_from_car, dtype=np.float64))
    c = np.asarray(centres, dtype=np.float64)[:, :3]
    e = c @ car_from_ref[:3, :3].T + car_from_ref[:3, 3]
    return np.arctan2(e[:, 1], e[:, 0])


def frame_boxes(info, min_points, name_map, sector):
    """(N, 8) LiDAR-frame boxes with model labels in column 7, kept as T trained with them (num_lidar_pts >= min_points, the
    nuScenes -> kitti ontology onto CLASSES) and inside the sector (right, left) about the vehicle's forward axis."""
    import numpy as np
    g = np.asarray(info['gt_boxes'], dtype=np.float64)
    if g.size == 0:
        return np.zeros((0, 8))
    g = g.reshape(-1, g.shape[-1])
    names = np.asarray(info['gt_names'])
    keep = np.asarray(info['num_lidar_pts']) > min_points - 1
    model = np.array([name_map.get(n, None) for n in names], dtype=object)
    keep &= np.isin(model, CLASSES)
    g, model = g[keep], model[keep]
    if len(g) == 0:
        return np.zeros((0, 8))
    az = ego_azimuth(g[:, :3], info['ref_from_car'])
    m = (az >= -sector[0]) & (az <= sector[1])
    lab = np.array([CLASSES.index(n) + 1 for n in model[m]], dtype=np.float64)
    return np.concatenate([g[m, :7], lab[:, None]], axis=1)


def source_frames(t):
    """The nuScenes train infos T was trained on: each DATA_CONFIGS entry built as train.py builds it (VEHICLE filter)."""
    import os
    from pcdet.datasets import build_dataloader
    from pcdet.utils import common_utils
    out = {}
    cwd = os.getcwd()
    os.chdir(TOOLS)
    try:
        for name, dc in t.DATA_CONFIGS.items():
            ds, _, _ = build_dataloader(dc, t.CLASS_NAMES, 1, dist=False, workers=0, training=True,
                                        logger=common_utils.create_logger(), model_ontology=t.get('ONTOLOGY', None))
            out[name] = (list(ds.infos), int(dc.get('FILTER_MIN_POINTS_IN_GT', 0) or 0), dc.ONTOLOGY)
            del ds
    finally:
        os.chdir(cwd)
    return out


def cmd_srcdens():
    import pickle
    import item63_range_cuts as m63
    from pcdet.utils.ontology_mapping import get_ontology_mapping
    t = load_cfg(T_CFG)
    right, left, cal = kitti_sector(pickle.load(open(KITTI / 'kitti_infos_train.pkl', 'rb')))
    by, per, tokens = {}, {}, set()
    for name, (infos, min_pts, ont) in source_frames(t).items():
        nm = get_ontology_mapping(ont, t.ONTOLOGY)
        sub = {}
        for info in infos:
            assert info['token'] not in tokens, 'a frame in two source sets: %s' % info['token']
            tokens.add(info['token'])
            sub[info['token']] = frame_boxes(info, min_pts, nm, (right, left))
        per[name] = dict(frames=len(sub), min_points=min_pts, density=m63.per_frame_counts(sub, len(sub)))
        by.update(sub)
    res = dict(edges=list(m63.EDGES), sector_rad=[-right, left], sector_deg=[-float(right) * 57.29578, float(left) * 57.29578],
               kitti_calibration_medians=cal, frames=len(by), density=m63.per_frame_counts(by, len(by)), per_source=per)
    OUT.mkdir(parents=True, exist_ok=True)
    json.dump(res, open(OUT / 'source_density.json', 'w'), indent=1)
    print(json.dumps(res, indent=1))


