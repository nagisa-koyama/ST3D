def target_fov(ps, infos, shift_z):
    """{frame: floor-pass boxes inside the camera FOV} (raw LiDAR frame, SHIFT_COOR z removed) and all boxes, KITTI train."""
    import numpy as np
    import item63_range_cuts as m63
    shapes = {i['point_cloud']['lidar_idx']: i['image']['image_shape'] for i in infos}
    fov, allb = {}, {}
    for fid, v in ps.items():
        b = np.asarray(v['gt_boxes']).reshape(-1, 9).copy()
        b[:, 2] -= shift_z
        allb[fid] = b
        fov[fid] = b[m63.fov_mask(b[:, :3], m63.calib_of('training', fid), shapes[fid])]
    return fov, allb


