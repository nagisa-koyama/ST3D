def item37d():
    import json
    s2 = json.load(open(M.STATS['pandaset']))['pitch']            # nuScenes slopes and the Boston share (31406)
    nus, prob = s2['nuscenes_slopes_deg'], s2['pitch_prob']
    for target in ('lyft64', 'lyft40'):
        oracle, block, d, short, desc = M.TARGET[target]
        st = json.load(open(M.STATS[target]))
        fsign = float(st['ground']['forward_axis_sign_along_x'])
        assert fsign == -1.0, 'Lyft LIDAR_TOP x is expected to point backward'
        lyft = float(st['ground']['forward_slope_deg']['median'])    # rise ahead, sign-corrected by the stats job
        rise = [round(nus['boston'] - lyft, 2), round(nus['singapore'] - lyft, 2)]
        angle = [round(fsign * r, 2) for r in rise]                   # about +x
        pivot = [0.0, 0.0, float(st['shift_coor'][2])]
        note = ('# ANALYSIS training row, FACTOR-SWAP on %s (experiments_md 20261003_05 §5 item 37d, design fixed 2026-11-08 01:40\n'
                '# JST): %s with ONE factor of its TRAINING data set to the nuScenes value, training only\n'
                '# (TRAIN_FACTOR_SWAP, pcdet/datasets/loader_factor_swap.py), scored on the target\'s UNPERTURBED val in-run.\n'
                '# Contribution = AP(oracle) - AP(this row), Car BEV R40 IoU 0.7, one seed. Target TRAIN labels train this row:\n'
                '# labelled analysis. Generated by analysis/make_item37_configs.py from %s and %s.\n'
                '# This arm: R5, A1 mounting attitude (pitch), as PandaSet R5 (item 34): per frame the ground ahead rises by\n'
                '# %+.2f deg (nuScenes Boston forward ground slope %+.2f - %s %+.2f, 20261004_02\'s estimator on all %d TRAIN\n'
                '# frames) with the Boston share of nuScenes TRAIN frames (%.4f, 31406), else %+.2f deg (Singapore %+.2f - %s).\n'
                '# Lyft\'s LIDAR_TOP x points BACKWARD (forward axis sign along x %.0f), so PITCH_DEG about +x is the negative of\n'
                '# the rise: %s. Points and box centres together, boxes upright, about the lateral axis through the sensor, PIVOT\n'
                '# %s in the loader frame AFTER SHIFT_COOR. The oracle\'s box set is kept (its zero-point count is taken before\n'
                '# the pitch).\n'
                % (target, desc, M.STATS[target], M.STATS['pandaset'], rise[0], nus['boston'], target, lyft,
                   st['ground']['frames_fitted'], prob[0], rise[1], nus['singapore'], target, fsign, angle, pivot))
        swap = {'PITCH_DEG': angle, 'PITCH_PROB': [M.r4(prob[0]), M.r4(1.0 - M.r4(prob[0]))], 'PIVOT': pivot}
        M.dump(os.path.join(d, 'centerpoint-factorswap-%s-r5-pitch.yaml' % short), note,
               {'_BASE_CONFIG_': oracle, **M.nest(block, {'TRAIN_FACTOR_SWAP': swap})})


